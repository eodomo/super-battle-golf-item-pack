"""Builds the Sniper Rifle model (a long Halo-style anti-materiel rifle with a big scope).

    blender --background --factory-startup --python blender/SniperRifle/build_sniper_rifle.py

Outputs Assets/SniperRifle/sniper_rifle.obj/.mtl/_icon.png and blender/SniperRifle/sniper_rifle.blend.
Forward is +Y (Blender), up is +Z, origin at the grip.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "SniperRifle"
NAME = "sniper_rifle"
COLORS = {
    "Gunmetal": (0.33, 0.35, 0.38),
    "Dark": (0.11, 0.11, 0.12),
    "Steel": (0.62, 0.64, 0.67),
    "Lens": (0.35, 0.75, 0.95),
}
ORDER = ["Gunmetal", "Dark", "Steel", "Lens"]
GUNMETAL, DARK, STEEL, LENS = range(4)


def along_y(x, y, z):
    return Matrix.Translation((x, y, z)) @ Matrix.Rotation(math.radians(-90), 4, "X")


def at(x, y, z, tilt_deg=0.0):
    return Matrix.Translation((x, y, z)) @ Matrix.Rotation(math.radians(tilt_deg), 4, "X")


def main():
    scene = common.fresh_scene("SniperRifle")
    materials = common.make_materials("SR_", COLORS, ORDER, roughness=0.4)
    parts = []
    z = 0.07  # bore height above the grip

    # Receiver: a long slab with a darker upper rail.
    parts.append(common.box((0.07, 0.62, 0.1), at(0, 0.08, z), GUNMETAL))
    parts.append(common.box((0.05, 0.56, 0.025), at(0, 0.1, z + 0.062), DARK))
    # Barrel shroud, barrel and muzzle brake.
    parts.append(common.box((0.06, 0.3, 0.07), at(0, 0.53, z + 0.005), GUNMETAL))
    parts.append(common.cylinder(0.016, 0.016, 0.5, along_y(0, 0.92, z + 0.01), 16, STEEL))
    parts.append(common.box((0.05, 0.09, 0.045), at(0, 1.2, z + 0.01), DARK))
    for dy in (-0.025, 0.0, 0.025):
        parts.append(common.box((0.056, 0.01, 0.012), at(0, 1.2 + dy, z + 0.01), STEEL))
    # Scope: a big tube on two mounts with lenses at both ends.
    sz = z + 0.135
    parts.append(common.cylinder(0.034, 0.034, 0.32, along_y(0, 0.12, sz), 20, DARK))
    parts.append(common.cylinder(0.045, 0.034, 0.07, along_y(0, 0.31, sz), 20, DARK))
    parts.append(common.cylinder(0.04, 0.034, 0.06, along_y(0, -0.07, sz), 20, DARK))
    parts.append(common.cylinder(0.04, 0.04, 0.005, along_y(0, 0.347, sz), 20, LENS))
    parts.append(common.cylinder(0.035, 0.035, 0.005, along_y(0, -0.102, sz), 20, LENS))
    for y in (0.02, 0.22):
        parts.append(common.box((0.03, 0.03, 0.06), at(0, y, z + 0.085), GUNMETAL))
    # Magazine (behind the grip, bullpup style), grip, trigger guard.
    parts.append(common.box((0.05, 0.1, 0.14), at(0, -0.12, z - 0.1, -8), DARK))
    parts.append(common.box((0.045, 0.06, 0.13), at(0, 0.0, -0.01, -15), DARK))
    parts.append(common.box((0.02, 0.09, 0.012), at(0, 0.06, z - 0.07), STEEL))
    # Stock with a cheek rest and butt pad.
    parts.append(common.box((0.06, 0.3, 0.11), at(0, -0.36, z - 0.01), GUNMETAL))
    parts.append(common.box((0.05, 0.18, 0.04), at(0, -0.33, z + 0.065), DARK))
    parts.append(common.box((0.065, 0.025, 0.14), at(0, -0.52, z - 0.015), DARK))

    rifle = common.merge(scene, "SniperRifle", parts, materials)
    assets = common.assets_dir(KEY)
    tris = common.export_obj(rifle, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Sniper Rifle - generated by build_sniper_rifle.py")
    # Icon only (already exported): tilt the rifle so it lies diagonally across the square icon.
    rifle.rotation_euler = (math.radians(32), 0.0, 0.0)
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=1.6,
                       look_at=(0, 0.25, 0.24), cam_offset=(1.5, -0.35, 0.25))
    rifle.rotation_euler = (0.0, 0.0, 0.0)
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    d = rifle.dimensions
    print(f"RESULT {NAME}: {tris} triangles, dimensions {d.x:.3f} x {d.y:.3f} x {d.z:.3f} m")


main()
