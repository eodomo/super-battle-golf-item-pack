"""Builds the Emergency Meeting models: the handheld emergency button (a metal box with a hazard-striped collar
and a big red dome button) and the round meeting table everyone gets pulled to, with the button in the middle.

    Run through the Blender MCP (exec with __file__ set to this path).

Outputs Assets/EmergencyMeeting/emergency_button.obj/.mtl/_icon.png, meeting_table.obj/.mtl and
blender/EmergencyMeeting/emergency_meeting.blend. Up is +Z. The button's origin is the bottom of its box (about
0.17 m across); the table's is the floor under its middle (2.3 m across, 0.8 m tall).
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "EmergencyMeeting"
COLORS = {
    "Metal": (0.55, 0.58, 0.62),
    "DarkMetal": (0.25, 0.27, 0.3),
    "Yellow": (0.98, 0.8, 0.1),
    "Black": (0.08, 0.08, 0.09),
    "Red": (0.9, 0.08, 0.08),
    "RedDark": (0.55, 0.04, 0.05),
    "Table": (0.72, 0.8, 0.86),
    "TableRim": (0.45, 0.52, 0.6),
}
ORDER = ["Metal", "DarkMetal", "Yellow", "Black", "Red", "RedDark", "Table", "TableRim"]
METAL, DARKMETAL, YELLOW, BLACK, RED, REDDARK, TABLE, TABLERIM = range(8)


def button(base):
    """The button unit, sitting on z = 0 of <base>."""
    p = [
        common.box((0.17, 0.17, 0.07), base @ Matrix.Translation((0, 0, 0.035)), METAL, bevel=0.012),
        common.box((0.175, 0.175, 0.012), base @ Matrix.Translation((0, 0, 0.012)), DARKMETAL, bevel=0.004),
        common.cylinder(0.068, 0.068, 0.016, base @ Matrix.Translation((0, 0, 0.078)), 32, BLACK),
    ]
    # Hazard stripes around the collar: alternating yellow wedges on the black ring.
    for k in range(12):
        if k % 2:
            continue
        a = 2 * math.pi * k / 12
        m = base @ Matrix.Translation((math.cos(a) * 0.062, math.sin(a) * 0.062, 0.079)) @ Matrix.Rotation(a + 0.5, 4, "Z")
        p.append(common.box((0.014, 0.03, 0.018), m, YELLOW))
    p.append(common.cylinder(0.052, 0.052, 0.02, base @ Matrix.Translation((0, 0, 0.094)), 32, REDDARK))
    p.append(common.sphere(0.05, base @ Matrix.Translation((0, 0, 0.1)) @ Matrix.Scale(0.6, 4, (0, 0, 1)), 32, 16, RED))
    return p


def table():
    p = [
        common.cylinder(0.55, 0.6, 0.05, Matrix.Translation((0, 0, 0.025)), 48, TABLERIM),
        common.cylinder(0.16, 0.16, 0.7, Matrix.Translation((0, 0, 0.4)), 24, TABLERIM),
        common.cylinder(1.15, 1.15, 0.08, Matrix.Translation((0, 0, 0.76)), 64, TABLERIM),
        common.cylinder(1.08, 1.08, 0.085, Matrix.Translation((0, 0, 0.765)), 64, TABLE),
        common.cylinder(0.16, 0.2, 0.04, Matrix.Translation((0, 0, 0.825)), 32, DARKMETAL),
    ]
    p += button(Matrix.Translation((0, 0, 0.845)) @ Matrix.Scale(1.6, 4))
    return p


def main():
    scene = common.fresh_scene("EmergencyMeeting")
    mats = common.make_materials("EM_", COLORS, ORDER, roughness=0.4)
    flat = (YELLOW, BLACK, DARKMETAL)
    btn = common.merge(scene, "EmergencyButton", button(Matrix.Identity(4)), mats, flat_materials=flat)
    assets = common.assets_dir(KEY)
    tris = common.export_obj(btn, os.path.join(assets, "emergency_button.obj"), os.path.join(assets, "emergency_button.mtl"),
                             COLORS, ORDER, "Emergency Meeting button - generated by build_emergency_meeting.py")
    common.render_icon(scene, os.path.join(assets, "emergency_button_icon.png"), ortho_scale=0.26,
                       look_at=(0, 0, 0.055), cam_offset=(0.8, -1.0, 0.75))
    tbl = common.merge(scene, "MeetingTable", table(), mats, flat_materials=flat)
    ttris = common.export_obj(tbl, os.path.join(assets, "meeting_table.obj"), os.path.join(assets, "meeting_table.mtl"),
                              COLORS, ORDER, "Emergency Meeting table - generated by build_emergency_meeting.py")
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, "emergency_meeting.blend"), scene)
    return f"button {tris} tris {tuple(round(v, 3) for v in btn.dimensions)}; table {ttris} tris {tuple(round(v, 3) for v in tbl.dimensions)}"


RESULT = main()
print("RESULT", RESULT)
