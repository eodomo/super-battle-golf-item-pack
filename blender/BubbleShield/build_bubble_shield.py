"""Builds the Bubble Shield device (Halo 3 style): a squat olive canister on three splayed feet, with a glowing
amber emitter on top.

    Run through the Blender MCP (exec with __file__ set to this path).

Outputs Assets/BubbleShield/bubble_shield.obj/.mtl/_icon.png and blender/BubbleShield/bubble_shield.blend.
Up is +Z, origin at the bottom of the feet. About 0.26 m tall.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "BubbleShield"
NAME = "bubble_shield"
COLORS = {
    "Olive": (0.36, 0.4, 0.27),
    "Dark": (0.16, 0.17, 0.16),
    "Metal": (0.62, 0.63, 0.6),
    "Glow": (1.0, 0.78, 0.25),
    "Stripe": (0.95, 0.7, 0.15),
}
ORDER = ["Olive", "Dark", "Metal", "Glow", "Stripe"]
OLIVE, DARK, METAL, GLOW, STRIPE = range(5)


def build():
    p = []
    # Feet: three splayed struts with pads.
    for k in range(3):
        a = 2 * math.pi * k / 3
        strut = (Matrix.Translation((math.cos(a) * 0.0825, math.sin(a) * 0.0825, 0.03))
                 @ Matrix.Rotation(a, 4, "Z") @ Matrix.Rotation(math.radians(-45), 4, "Y"))
        p.append(common.box((0.018, 0.022, 0.075), strut, DARK, bevel=0.004))
        pad = Matrix.Translation((math.cos(a) * 0.105, math.sin(a) * 0.105, 0.006))
        p.append(common.cylinder(0.022, 0.018, 0.012, pad, 12, METAL))
    # Body: base ring, olive canister, stripe band, upper collar.
    p.append(common.cylinder(0.075, 0.075, 0.03, Matrix.Translation((0, 0, 0.06)), 24, DARK))
    p.append(common.cylinder(0.068, 0.06, 0.1, Matrix.Translation((0, 0, 0.125)), 24, OLIVE))
    p.append(common.cylinder(0.0695, 0.0675, 0.014, Matrix.Translation((0, 0, 0.11)), 24, STRIPE))
    p.append(common.cylinder(0.064, 0.05, 0.025, Matrix.Translation((0, 0, 0.187)), 24, METAL))
    # Side vents.
    for k in range(4):
        a = 2 * math.pi * k / 4 + math.pi / 4
        vent = Matrix.Translation((math.cos(a) * 0.064, math.sin(a) * 0.064, 0.145)) @ Matrix.Rotation(a, 4, "Z")
        p.append(common.box((0.01, 0.03, 0.035), vent, DARK, bevel=0.003))
    # Emitter: a glowing amber dome inside a ring of prongs.
    p.append(common.sphere(0.04, Matrix.Translation((0, 0, 0.205)), 20, 12, GLOW))
    for k in range(6):
        a = 2 * math.pi * k / 6
        prong = (Matrix.Translation((math.cos(a) * 0.047, math.sin(a) * 0.047, 0.225))
                 @ Matrix.Rotation(a, 4, "Z") @ Matrix.Rotation(math.radians(-18), 4, "Y"))
        p.append(common.box((0.008, 0.014, 0.05), prong, METAL, bevel=0.002))
    return p


def main():
    scene = common.fresh_scene("BubbleShield")
    mats = common.make_materials("BS_", COLORS, ORDER, roughness=0.45)
    obj = common.merge(scene, "BubbleShield", build(), mats, flat_materials=(DARK,))
    assets = common.assets_dir(KEY)
    tris = common.export_obj(obj, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Bubble Shield - generated by build_bubble_shield.py")
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=0.34,
                       look_at=(0, 0, 0.125), cam_offset=(0.9, -1.1, 0.55))
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    return f"{NAME}: {tris} triangles, dims {tuple(round(v, 3) for v in obj.dimensions)}"


RESULT = main()
print("RESULT", RESULT)
