"""Builds the Power Sword (a club cosmetic) and its menu icon.

Run it through the Blender MCP (execute_blender_code with runpy.run_path) or headless:

    blender --background --factory-startup --python blender/PowerRanger/build_sword.py

Outputs Assets/PowerRanger/sword.obj/.mtl and sword_icon.png.
Club models in the game run along Unity +Z from the grip (z = 0) to the tip (about z = 1.04), with the blade's
edge towards Unity +Y and its flat sides facing +-X. In Blender (X, Y, Z) = (-Ux, -Uz, Uy), so the sword runs
towards -Y with the edge up (+Z). Materials become cells of a small palette texture in game: the first one
(Accent) takes the ranger's color, the rest are fixed.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bpy  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "PowerRanger"
NAME = "sword"
COLORS = {
    "Accent": (0.86, 0.09, 0.11),
    "Silver": (0.80, 0.84, 0.90),
    "Gold": (0.93, 0.72, 0.16),
    "Dark": (0.10, 0.10, 0.12),
}
ORDER = ["Accent", "Silver", "Gold", "Dark"]
ACCENT, SILVER, GOLD, DARK = range(4)


def at(x=0.0, l=0.0, z=0.0):
    """Position by distance along the sword l (Blender -Y), height z and side x."""
    return Matrix.Translation((x, -l, z))


ALONG = Matrix.Rotation(math.pi / 2, 4, "X")  # turns a cylinder's Z axis into the sword's -Y axis


def build(scene, materials):
    parts = []
    # Pommel and grip with three colored wraps.
    parts.append(common.sphere(0.048, at(l=-0.06), segments=20, rings=12, material=GOLD))
    parts.append(common.cylinder(0.032, 0.032, 0.26, at(l=0.09) @ ALONG, segments=20, material=DARK))
    for l in (0.01, 0.09, 0.17):
        parts.append(common.cylinder(0.037, 0.037, 0.03, at(l=l) @ ALONG, segments=20, material=ACCENT))

    # Winged crossguard (the wings sweep up and down), with a gem on each face.
    parts.append(common.box((0.05, 0.07, 0.17), at(l=0.225), material=GOLD, bevel=0.012))
    for sign in (-1, 1):
        wing = at(l=0.225, z=sign * 0.10) @ Matrix.Rotation(sign * math.radians(-18), 4, "X")
        parts.append(common.box((0.045, 0.085, 0.11), wing, material=GOLD, bevel=0.012))
        parts.append(common.sphere(0.032, at(sign * 0.028, 0.225, 0.0), segments=16, rings=10, material=ACCENT))

    # Blade: a tapering outline (distance along, height) extruded across its thickness, with a gold collar at its base.
    parts.append(common.box((0.07, 0.05, 0.14), at(l=0.275), material=GOLD, bevel=0.01))
    outline = [(-0.30, -0.060), (-0.30, 0.075), (-0.90, 0.080), (-1.045, 0.014), (-0.90, -0.056)]
    parts.append(common.prism(outline, 0.07, material=SILVER, bevel=0.006))
    # A colored stripe along the blade's flat sides.
    for sign in (-1, 1):
        parts.append(common.box((0.004, 0.55, 0.014), at(sign * 0.036, 0.62, 0.012), material=ACCENT))

    return common.merge(scene, "PowerSword", parts, materials, flat_materials=(SILVER,))


def main():
    scene = common.fresh_scene("PowerSword")
    materials = common.make_materials("PS_", COLORS, ORDER, roughness=0.35)
    sword = build(scene, materials)
    assets = common.assets_dir(KEY)
    tris = common.export_obj(sword, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Power Sword - generated by build_sword.py")
    print(f"RESULT {NAME}: {tris} triangles, dimensions {tuple(round(d, 3) for d in sword.dimensions)}")
    # Diagonal pose about the sword's middle, seen from the side.
    from mathutils import Euler, Vector
    middle = Vector((0, -0.45, 0))
    rot = Euler((math.radians(38), 0, 0))
    sword.rotation_euler = rot
    sword.location = middle - rot.to_matrix() @ middle
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=1.35, look_at=tuple(middle),
                       cam_offset=(1.0, 0.0, 0.0))
    sword.rotation_euler = (0, 0, 0)
    sword.location = (0, 0, 0)


main()
