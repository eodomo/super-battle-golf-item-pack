"""Builds the Boogie Bomb model: a mirrored disco ball grenade with a purple cap, lever and pull ring.

    blender --background --factory-startup --python blender/BoogieBomb/build_boogie_bomb.py

Outputs Assets/BoogieBomb/boogie_bomb.obj/.mtl/_icon.png and blender/BoogieBomb/boogie_bomb.blend.
Up is +Z, origin at the ball's center. About 0.26 m across.
"""
import math
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bmesh  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "BoogieBomb"
NAME = "boogie_bomb"
COLORS = {
    "Mirror": (0.78, 0.8, 0.85),
    "MirrorBright": (0.97, 0.97, 1.0),
    "MirrorDark": (0.45, 0.47, 0.55),
    "Pink": (1.0, 0.35, 0.75),
    "Cyan": (0.35, 0.9, 1.0),
    "Purple": (0.5, 0.2, 0.85),
    "Metal": (0.7, 0.68, 0.62),
}
ORDER = ["Mirror", "MirrorBright", "MirrorDark", "Pink", "Cyan", "Purple", "Metal"]
MIRROR, BRIGHT, DARK, PINK, CYAN, PURPLE, METAL = range(7)
R = 0.13


def disco_ball():
    """A latitude/longitude grid of flat mirror tiles, each catching a different reflection."""
    rng = random.Random(77)
    bm = bmesh.new()
    rings, segments = 12, 24
    for i in range(rings):
        for j in range(segments):
            corners = []
            for di, dj in ((0, 0), (0, 1), (1, 1), (1, 0)):
                phi = math.pi * (i + di) / rings
                theta = 2 * math.pi * (j + dj) / segments
                corners.append(bm.verts.new((R * math.sin(phi) * math.cos(theta), R * math.sin(phi) * math.sin(theta), R * math.cos(phi))))
            face = bm.faces.new(corners)
            roll = rng.random()
            face.material_index = BRIGHT if roll < 0.18 else DARK if roll < 0.36 else PINK if roll < 0.43 else CYAN if roll < 0.5 else MIRROR
    bmesh.ops.remove_doubles(bm, verts=bm.verts, dist=1e-5)
    return bm


def build():
    p = [disco_ball()]
    # Grenade top: purple cap, metal fuse body, lever down the side, and the pull ring.
    p.append(common.cylinder(0.055, 0.045, 0.05, Matrix.Translation((0, 0, R + 0.012)), 20, PURPLE))
    p.append(common.cylinder(0.03, 0.03, 0.04, Matrix.Translation((0, 0, R + 0.055)), 16, METAL))
    lever = Matrix.Translation((0.045, 0, R - 0.005)) @ Matrix.Rotation(math.radians(-20), 4, "Y")
    p.append(common.box((0.014, 0.03, 0.12), lever, PINK, bevel=0.004))
    for k in range(16):  # the pull ring, as a chain of tiny cylinders
        a0, a1 = 2 * math.pi * k / 16, 2 * math.pi * (k + 1) / 16
        x0, z0 = math.cos(a0) * 0.032, math.sin(a0) * 0.032
        x1, z1 = math.cos(a1) * 0.032, math.sin(a1) * 0.032
        mid = ((x0 + x1) / 2 - 0.04, 0, (z0 + z1) / 2 + R + 0.075)
        angle = math.atan2(z1 - z0, x1 - x0)
        m = Matrix.Translation(mid) @ Matrix.Rotation(-angle, 4, "Y") @ Matrix.Rotation(math.radians(90), 4, "Y")
        p.append(common.cylinder(0.005, 0.005, 0.0135, m, 8, METAL))
    return p


def main():
    scene = common.fresh_scene("BoogieBomb")
    mats = common.make_materials("BB_", COLORS, ORDER, roughness=0.15)
    bomb = common.merge(scene, "BoogieBomb", build(), mats, flat_materials=(MIRROR, BRIGHT, DARK, PINK, CYAN))
    assets = common.assets_dir(KEY)
    tris = common.export_obj(bomb, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Boogie Bomb - generated by build_boogie_bomb.py")
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=0.42,
                       look_at=(0, 0, 0.04), cam_offset=(0.9, -1.1, 0.6))
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    print(f"RESULT {NAME}: {tris} triangles, dims {tuple(round(v, 3) for v in bomb.dimensions)}")


main()
