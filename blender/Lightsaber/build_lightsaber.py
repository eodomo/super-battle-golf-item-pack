"""Builds the Lightsaber hilt model and the three HUD icons (blue, green and red blades).

    blender --background --factory-startup --python blender/Lightsaber/build_lightsaber.py

Outputs Assets/Lightsaber/lightsaber_hilt.obj/.mtl, lightsaber_{blue,green,red}_icon.png and
blender/Lightsaber/lightsaber.blend. The hilt runs along +Z (the blade's direction; Unity +Y), centered on the
grip, with the emitter's top at z = 0.13 (LightsaberItem.HiltTop). The blade itself is built in code.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bpy  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "Lightsaber"
NAME = "lightsaber_hilt"
COLORS = {
    "Silver": (0.78, 0.79, 0.81),
    "Black": (0.09, 0.09, 0.10),
    "Steel": (0.42, 0.44, 0.48),
    "Red": (0.86, 0.12, 0.10),
}
ORDER = ["Silver", "Black", "Steel", "Red"]
SILVER, BLACK, STEEL, RED = range(4)
BLADES = {
    "blue": (0.2, 0.5, 1.0),
    "green": (0.25, 1.0, 0.3),
    "red": (1.0, 0.12, 0.1),
}
TOP = 0.13


def at(z):
    return Matrix.Translation((0, 0, z))


def build_hilt(scene, materials):
    parts = []
    # Pommel and the main silver body.
    parts.append(common.cylinder(0.021, 0.024, 0.025, at(-0.1175), segments=24, material=STEEL))
    parts.append(common.cylinder(0.022, 0.022, 0.15, at(-0.03), segments=24, material=SILVER))
    # Black grip ridges along the lower half.
    for k in range(7):
        parts.append(common.cylinder(0.0245, 0.0245, 0.009, at(-0.095 + k * 0.016), segments=24, material=BLACK))
    # Neck, then the flared emitter shroud with its dark ring.
    parts.append(common.cylinder(0.019, 0.019, 0.03, at(0.06), segments=20, material=STEEL))
    parts.append(common.cylinder(0.022, 0.029, 0.04, at(0.095), segments=28, material=SILVER))
    parts.append(common.cylinder(0.029, 0.029, 0.006, at(TOP - 0.003), segments=28, material=BLACK))
    # Activation button and a small switch plate.
    parts.append(common.box((0.012, 0.012, 0.016), Matrix.Translation((0, -0.022, 0.02)), material=RED, bevel=0.002))
    parts.append(common.box((0.01, 0.006, 0.05), Matrix.Translation((0, -0.0225, -0.005)), material=BLACK, bevel=0.001))
    return common.merge(scene, "LightsaberHilt", parts, materials)


def blade_material(name, rgb, strength, alpha=1.0):
    """Emissive; with alpha < 1 it's a see-through glow (mixed with transparency)."""
    mat = bpy.data.materials.get(name) or bpy.data.materials.new(name)
    if mat.node_tree is None and hasattr(mat, "use_nodes"):
        mat.use_nodes = True
    nodes = mat.node_tree.nodes
    links = mat.node_tree.links
    nodes.clear()
    out = nodes.new("ShaderNodeOutputMaterial")
    emit = nodes.new("ShaderNodeEmission")
    emit.inputs["Color"].default_value = (*[common.srgb_to_linear(c) for c in rgb], 1.0)
    emit.inputs["Strength"].default_value = strength
    if alpha >= 1.0:
        links.new(emit.outputs["Emission"], out.inputs["Surface"])
        return mat
    clear = nodes.new("ShaderNodeBsdfTransparent")
    mix = nodes.new("ShaderNodeMixShader")
    mix.inputs["Fac"].default_value = alpha
    links.new(clear.outputs["BSDF"], mix.inputs[1])
    links.new(emit.outputs["Emission"], mix.inputs[2])
    links.new(mix.outputs["Shader"], out.inputs["Surface"])
    if hasattr(mat, "surface_render_method"):
        mat.surface_render_method = "BLENDED"
    return mat


def add_blade(scene, rgb):
    """Icon-only blade: a white-hot core inside a see-through colored glow, with rounded ends."""
    objs = []
    length = 0.6
    core_color = tuple(0.85 + 0.15 * c for c in rgb)
    for radius, color, strength, alpha, name in ((0.05, rgb, 3.0, 0.45, "Glow"), (0.032, rgb, 3.5, 0.8, "Mid"),
                                                  (0.017, core_color, 4.0, 1.0, "Core")):
        mat = blade_material(f"LS_Blade{name}", color, strength, alpha)
        bm = common.cylinder(radius, radius, length, at(TOP + length / 2), segments=24)
        bm_tip = common.sphere(radius, at(TOP + length), segments=24, rings=12)
        objs.append(common.merge(scene, f"Blade{name}", [bm, bm_tip], [mat]))
    return objs


def main():
    scene = common.fresh_scene("Lightsaber")
    materials = common.make_materials("LS_", COLORS, ORDER, roughness=0.3)
    hilt = build_hilt(scene, materials)

    assets = common.assets_dir(KEY)
    tris = common.export_obj(hilt, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Lightsaber hilt - generated by build_lightsaber.py")
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, "lightsaber.blend"), scene)

    # Icons: the lit saber lying diagonally, one per blade color.
    tilt = Matrix.Rotation(math.radians(45), 4, "Y")  # blade up and to the right, seen from -Y
    hilt.matrix_world = tilt
    camera_ready = False
    for color, rgb in BLADES.items():
        blade = add_blade(scene, rgb)
        for obj in blade:
            obj.matrix_world = tilt
        path = os.path.join(assets, f"lightsaber_{color}_icon.png")
        if not camera_ready:
            common.render_icon(scene, path, ortho_scale=0.8, look_at=(0.21, 0, 0.21), cam_offset=(0, -2, 0))
            camera_ready = True
        else:
            scene.render.filepath = path
            bpy.ops.render.render(write_still=True, scene=scene.name)
        for obj in blade:
            bpy.data.objects.remove(obj, do_unlink=True)
        print(f"RESULT wrote {path}")

    d = hilt.dimensions
    print(f"RESULT {NAME}: {tris} triangles, dimensions {d.x:.3f} x {d.y:.3f} x {d.z:.3f} m")


main()
