"""Builds the Predator Missile models: the rugged laptop you hold and the missile everyone sees.

    blender --background --factory-startup --python blender/PredatorMissile/build_predator.py [-- --preview <png>]

Outputs in Assets/PredatorMissile:
  predator_laptop.obj/.mtl/_icon.png   held item (forward +Y, origin at the hands)
  predator_missile.obj/.mtl            the missile, nose toward -Y (= +Z, forward, in Unity), origin at its middle
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bmesh  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix  # noqa: E402

KEY = "PredatorMissile"
LAPTOP_COLORS = {
    "Case": (0.24, 0.26, 0.22),     # olive-drab rugged case
    "Dark": (0.08, 0.08, 0.09),
    "Screen": (0.35, 0.55, 0.42),   # greyish thermal feed
    "Accent": (0.75, 0.62, 0.2),
}
LAPTOP_ORDER = ["Case", "Dark", "Screen", "Accent"]
MISSILE_COLORS = {
    "Body": (0.62, 0.64, 0.6),
    "Dark": (0.12, 0.12, 0.13),
    "Band": (0.85, 0.7, 0.15),
    "Nozzle": (0.3, 0.3, 0.32),
}
MISSILE_ORDER = ["Body", "Dark", "Band", "Nozzle"]


def along_y(x, y, z):
    return Matrix.Translation((x, y, z)) @ Matrix.Rotation(math.radians(-90), 4, "X")


def build_laptop():
    CASE, DARK, SCREEN, ACCENT = range(4)
    p = []
    p.append(common.box((0.36, 0.26, 0.035), Matrix.Translation((0, 0.05, 0.0)), CASE, bevel=0.01))   # base
    p.append(common.box((0.32, 0.13, 0.004), Matrix.Translation((0, 0.08, 0.019)), DARK))              # keyboard
    p.append(common.box((0.1, 0.06, 0.003), Matrix.Translation((0, -0.03, 0.019)), DARK))              # trackpad
    hinge = Matrix.Translation((0, 0.18, 0.02)) @ Matrix.Rotation(math.radians(-105), 4, "X")
    p.append(common.box((0.36, 0.24, 0.025), hinge @ Matrix.Translation((0, -0.12, 0.0)), CASE, bevel=0.01))  # lid
    p.append(common.box((0.3, 0.19, 0.004), hinge @ Matrix.Translation((0, -0.12, -0.014)), SCREEN))           # screen
    for x in (-0.17, 0.17):
        p.append(common.box((0.03, 0.05, 0.05), Matrix.Translation((x, 0.17, 0.02)), DARK, bevel=0.006))     # rugged corners
        p.append(common.box((0.03, 0.05, 0.05), Matrix.Translation((x, -0.07, 0.0)), DARK, bevel=0.006))
    p.append(common.box((0.12, 0.01, 0.012), Matrix.Translation((0, -0.081, 0.0)), ACCENT))                  # latch
    return p


def build_missile():
    BODY, DARK, BAND, NOZZLE = range(4)
    p = []
    p.append(common.cylinder(0.17, 0.17, 1.8, along_y(0, 0.2, 0), 24, BODY))                  # body
    p.append(common.cylinder(0.01, 0.17, 0.55, along_y(0, -0.975, 0), 24, BODY))              # nose cone (toward -Y)
    p.append(common.sphere(0.035, Matrix.Translation((0, -1.25, 0)), 10, 6, DARK))            # seeker tip
    p.append(common.cylinder(0.172, 0.172, 0.08, along_y(0, -0.4, 0), 24, BAND))              # warhead band
    p.append(common.cylinder(0.172, 0.172, 0.05, along_y(0, 0.6, 0), 24, DARK))
    p.append(common.cylinder(0.14, 0.11, 0.18, along_y(0, 1.19, 0), 20, NOZZLE))              # nozzle
    p.append(common.cylinder(0.09, 0.09, 0.02, along_y(0, 1.285, 0), 16, DARK))
    # Fins are drawn as side-view outlines (y along the body, z outward), then spun around the body axis.
    tail_fin = [(0.75, 0.15), (1.1, 0.15), (1.1, 0.42), (0.95, 0.42)]
    canard = [(-0.55, 0.15), (-0.35, 0.15), (-0.4, 0.27), (-0.5, 0.27)]
    for outline, thickness in ((tail_fin, 0.02), (canard, 0.015)):
        for k in range(4):
            fin = common.prism(outline, thickness, DARK)
            bmesh.ops.transform(fin, matrix=Matrix.Rotation(math.radians(45 + k * 90), 4, "Y"), verts=fin.verts)
            p.append(fin)
    return p


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    preview = argv[argv.index("--preview") + 1] if "--preview" in argv else None
    assets = common.assets_dir(KEY)

    scene = common.fresh_scene("PredatorLaptop")
    laptop = common.merge(scene, "PredatorLaptop", build_laptop(), common.make_materials("PL_", LAPTOP_COLORS, LAPTOP_ORDER))
    t1 = common.export_obj(laptop, os.path.join(assets, "predator_laptop.obj"), os.path.join(assets, "predator_laptop.mtl"),
                           LAPTOP_COLORS, LAPTOP_ORDER, "Predator laptop - generated by build_predator.py")

    missile_scene = common.fresh_scene("PredatorMissile")
    missile = common.merge(missile_scene, "PredatorMissile", build_missile(), common.make_materials("PM_", MISSILE_COLORS, MISSILE_ORDER))
    t2 = common.export_obj(missile, os.path.join(assets, "predator_missile.obj"), os.path.join(assets, "predator_missile.mtl"),
                           MISSILE_COLORS, MISSILE_ORDER, "Predator missile - generated by build_predator.py")

    # Icon: the missile diving diagonally (exported already, so tilting it here is safe).
    missile.rotation_euler = (math.radians(-35), 0.0, math.radians(20))
    common.render_icon(missile_scene, os.path.join(assets, "predator_laptop_icon.png"), ortho_scale=2.3,
                       look_at=(0, 0.1, 0), cam_offset=(3, -1.2, 1.2))
    if preview:
        common.render_icon(scene, preview, ortho_scale=0.6, look_at=(0, 0.05, 0.08), cam_offset=(0.7, -0.9, 0.6), size=512)
    missile.rotation_euler = (0, 0, 0)
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, "predator_laptop.blend"), scene)
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, "predator_missile.blend"), missile_scene)
    print(f"RESULT laptop {t1} tris, dims {tuple(round(v, 3) for v in laptop.dimensions)}; missile {t2} tris, dims {tuple(round(v, 3) for v in missile.dimensions)}")


main()
