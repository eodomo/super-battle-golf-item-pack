"""Builds the Blue Shell model: a blue spiny shell with a cream rim, white spikes and feathered wings.

    blender --background --factory-startup --python blender/BlueShell/build_blue_shell.py [-- --preview <png>]

Outputs Assets/BlueShell/blue_shell.obj/.mtl/_icon.png and blender/BlueShell/blue_shell.blend.
Up is +Z, wings along X, origin at the bottom center. About 1 m across the shell (2.2 m with wings).
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bmesh  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402

KEY = "BlueShell"
NAME = "blue_shell"
COLORS = {
    "Blue": (0.13, 0.36, 0.95),
    "DarkBlue": (0.07, 0.2, 0.62),
    "Cream": (0.98, 0.95, 0.85),
    "White": (0.98, 0.98, 0.98),
}
ORDER = ["Blue", "DarkBlue", "Cream", "White"]
BLUE, DARK_BLUE, CREAM, WHITE = range(4)
R = 0.5   # shell radius
H = 0.42  # dome height


def dome_point(theta, phi):
    """Point on the dome: theta around, phi from the top (0) to the rim (pi/2)."""
    return Vector((R * math.sin(phi) * math.cos(theta), R * math.sin(phi) * math.sin(theta), 0.12 + H * math.cos(phi)))


def spike(theta, phi, length, radius):
    base = dome_point(theta, phi)
    normal = Vector((math.sin(phi) * math.cos(theta) / R, math.sin(phi) * math.sin(theta) / R, math.cos(phi) / H)).normalized()
    rot = normal.to_track_quat("Z", "Y").to_matrix().to_4x4()
    return common.cylinder(radius, 0.0, length, Matrix.Translation(base + normal * (length * 0.5 - 0.02)) @ rot, 12, WHITE)


def wing(side):
    """A feathered wing: three stacked feather layers fanning out and up."""
    parts = []
    for k, (length, height, rise) in enumerate(((0.8, 0.38, 0.1), (0.66, 0.3, 0.18), (0.5, 0.24, 0.26))):
        outline = [(0.0, 0.0), (length * 0.55, -0.04), (length, height * 0.35), (length * 0.85, height * 0.7),
                   (length * 0.5, height * 0.95), (0.0, height)]
        # Outline is drawn in the (y, z) plane by prism(); lay it out along X instead and tilt it upward.
        feather = common.prism(outline, 0.025, WHITE)
        bmesh.ops.transform(feather, matrix=Matrix.Rotation(math.radians(-90), 4, "Z"), verts=feather.verts)
        tilt = Matrix.Rotation(math.radians(-25 - k * 12), 4, "Y")
        place = Matrix.Translation((0.45, 0.06 - k * 0.07, 0.3 + rise * 0.3)) @ tilt
        if side < 0:
            place = Matrix.Scale(-1, 4, Vector((1, 0, 0))) @ place
        bmesh.ops.transform(feather, matrix=place, verts=feather.verts)
        if side < 0:
            bmesh.ops.reverse_faces(feather, faces=feather.faces)  # mirroring flips the winding
        parts.append(feather)
    return parts


def build():
    p = []
    # Dome: a squashed sphere's top half, sitting on the rim.
    dome = bmesh.new()
    bmesh.ops.create_uvsphere(dome, u_segments=40, v_segments=20, radius=1.0)
    bmesh.ops.delete(dome, geom=[v for v in dome.verts if v.co.z < -0.01], context="VERTS")
    bmesh.ops.scale(dome, vec=(R, R, H), verts=dome.verts)
    bmesh.ops.translate(dome, vec=(0, 0, 0.12), verts=dome.verts)
    p.append(common.set_material(dome, BLUE))
    # A darker blue band around the bottom of the dome.
    p.append(common.cylinder(R + 0.012, R - 0.03, 0.09, Matrix.Translation((0, 0, 0.19)), 40, DARK_BLUE))
    # Cream rim and underside.
    p.append(common.cylinder(R + 0.05, R + 0.05, 0.1, Matrix.Translation((0, 0, 0.1)), 40, CREAM))
    p.append(common.cylinder(R - 0.02, R * 0.8, 0.08, Matrix.Translation((0, 0, 0.03)), 40, CREAM))
    # Spikes: one on top, six around the middle.
    p.append(spike(0.0, 0.0, 0.3, 0.1))
    for k in range(6):
        p.append(spike(k * math.pi / 3, 0.66, 0.26, 0.09))
    # Wings.
    for side in (1, -1):
        p.extend(wing(side))
    return p


def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    preview = argv[argv.index("--preview") + 1] if "--preview" in argv else None
    scene = common.fresh_scene("BlueShell")
    shell = common.merge(scene, "BlueShell", build(), common.make_materials("BS_", COLORS, ORDER, roughness=0.3))
    assets = common.assets_dir(KEY)
    tris = common.export_obj(shell, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Blue Shell - generated by build_blue_shell.py")
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=2.45,
                       look_at=(0, 0, 0.4), cam_offset=(1.0, -2.4, 1.0))
    if preview:
        common.render_icon(scene, preview, ortho_scale=2.2, look_at=(0, 0, 0.3), cam_offset=(1.6, -2.4, 1.0), size=512)
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    print(f"RESULT {NAME}: {tris} triangles, dims {tuple(round(v, 3) for v in shell.dimensions)}")


main()
