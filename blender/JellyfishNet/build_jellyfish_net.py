"""Builds the Jellyfish Net (SpongeBob): a wooden pole with a ring on the end and a pink mesh bag.

    Run through the Blender MCP (exec with __file__ set to this path).

Outputs Assets/JellyfishNet/jellyfish_net.obj/.mtl/_icon.png and blender/JellyfishNet/jellyfish_net.blend.
Blender Z is up, which is the OBJ's +Y: the pole runs along it from the origin (the grip is at about 0.25 m), the
ring's opening faces Blender -Y (the OBJ's +Z, the way the player faces) and the bag trails behind it.
"""
import math
import os
import sys

import bmesh

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import common  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402

KEY = "JellyfishNet"
NAME = "jellyfish_net"
COLORS = {
    "Bamboo": (0.84, 0.72, 0.38),
    "Node": (0.58, 0.46, 0.2),
    "Cord": (0.97, 0.97, 0.95),
}
ORDER = ["Bamboo", "Node", "Cord"]
BAMBOO, NODE, CORD = range(3)

POLE = 1.0          # from the butt to where the ring starts
RING_R = 0.2        # ring radius
BAG_DEPTH = 0.3
CORD_R = 0.005      # thickness of the net's strings


def strand(a, b, radius, material):
    """A thin round rod from point a to point b."""
    a, b = Vector(a), Vector(b)
    d = b - a
    m = Matrix.Translation((a + b) / 2) @ d.to_track_quat("Z", "Y").to_matrix().to_4x4()
    return common.cylinder(radius, radius, d.length, m, segments=5, material=material)


def build(kind="full"):
    """kind: full (frame + bag), frame (pole and ring) or bag (just the net)."""
    parts = []
    if kind == "bag":
        return bag_parts()
    # Bamboo pole: a slightly tapering cane with darker nodes (rings) every 20 cm.
    parts.append(common.cylinder(0.021, 0.016, POLE, Matrix.Translation((0, 0, POLE / 2)), segments=10, material=BAMBOO))
    for i in range(5):
        z = 0.08 + i * 0.2
        r = 0.021 - 0.005 * (z / POLE) + 0.004
        parts.append(common.cylinder(r, r, 0.022, Matrix.Translation((0, 0, z)), segments=10, material=NODE))

    # The ring: a bent bamboo hoop standing in the XZ plane, its bottom touching the pole's end.
    center = Vector((0, 0, POLE + RING_R))
    bm = bmesh.new()
    major, minor = 36, 6
    rings = []
    for i in range(major):
        a = 2 * math.pi * i / major
        c = center + Vector((math.sin(a) * RING_R, 0, -math.cos(a) * RING_R))
        radial = (c - center).normalized()
        row = []
        for j in range(minor):
            b = 2 * math.pi * j / minor
            p = c + radial * (math.cos(b) * 0.014) + Vector((0, 1, 0)) * (math.sin(b) * 0.014)
            row.append(bm.verts.new(p))
        rings.append(row)
    for i in range(major):
        for j in range(minor):
            bm.faces.new((rings[i][j], rings[(i + 1) % major][j], rings[(i + 1) % major][(j + 1) % minor], rings[i][(j + 1) % minor]))
    parts.append(common.set_material(bm, BAMBOO))

    if kind == "frame":
        return parts
    return parts + bag_parts()


def bag_parts():
    parts = []
    center = Vector((0, 0, POLE + RING_R))
    # The net: thin white strings in a half-ellipsoid trailing behind the ring (toward Blender +Y). No solid
    # faces, so it's see-through.
    seg, lat = 16, 6
    grid = []
    for k in range(lat + 1):
        t = k / lat * (math.pi / 2)
        radius = RING_R * math.cos(t)
        depth = BAG_DEPTH * math.sin(t)
        grid.append([center + Vector((math.sin(2 * math.pi * i / seg) * radius, depth, -math.cos(2 * math.pi * i / seg) * radius)) for i in range(seg)])
    for k in range(lat):
        for i in range(seg):
            parts.append(strand(grid[k][i], grid[k + 1][i], CORD_R, CORD))                     # meridians
            if k > 0:
                parts.append(strand(grid[k][i], grid[k][(i + 1) % seg], CORD_R, CORD))         # latitudes
    return parts


def main():
    scene = common.fresh_scene("JellyfishNet")
    mats = common.make_materials("JN_", COLORS, ORDER, roughness=0.6)
    obj = common.merge(scene, "JellyfishNet", build(), mats, flat_materials=())
    assets = common.assets_dir(KEY)
    tris = common.export_obj(obj, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Jellyfish Net - generated by build_jellyfish_net.py")
    # The held model is the frame with the net as its own part (so the net can be swapped for the hanging one).
    for kind in ("frame",):
        part = common.merge(scene, kind, build(kind), mats, flat_materials=())
        common.export_obj(part, os.path.join(assets, f"{NAME}_{kind}.obj"), os.path.join(assets, f"{NAME}_{kind}.mtl"),
                          COLORS, ORDER, f"Jellyfish Net {kind}")
        scene.collection.objects.unlink(part)
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=1.7,
                       look_at=(0, 0.1, 0.65), cam_offset=(-1.0, -1.6, 0.6))
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    return f"{NAME}: {tris} triangles, dims {tuple(round(v, 3) for v in obj.dimensions)}"


RESULT = main()
print("RESULT", RESULT)
