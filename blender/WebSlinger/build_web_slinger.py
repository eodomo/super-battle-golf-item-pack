"""Builds the Web Slinger model (a Spider-Man style web shooter glove) and its HUD icon.

    blender --background --factory-startup --python blender/WebSlinger/build_web_slinger.py

Outputs Assets/WebSlinger/web_slinger.obj/.mtl, web_slinger_icon.png and blender/WebSlinger/web_slinger.blend.
The glove stands along +Z (Unity +Y), centered on the grip; the web shooter nozzle points up out of the top.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bpy  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402

KEY = "WebSlinger"
NAME = "web_slinger"
COLORS = {
    "Red": (0.80, 0.07, 0.09),
    "Blue": (0.09, 0.20, 0.66),
    "Black": (0.04, 0.04, 0.05),
    "Silver": (0.76, 0.78, 0.82),
    "White": (0.95, 0.95, 0.95),
}
ORDER = ["Red", "Blue", "Black", "Silver", "White"]
RED, BLUE, BLACK, SILVER, WHITE = range(5)

R = 0.042  # glove radius


def at(x=0.0, y=0.0, z=0.0):
    return Matrix.Translation((x, y, z))


def build(scene, materials):
    parts = []
    # Red glove body with a blue cuff at the bottom and a blue band under the cap.
    parts.append(common.cylinder(R, R, 0.10, at(z=0.0), segments=32, material=RED))
    parts.append(common.cylinder(R + 0.004, R + 0.004, 0.04, at(z=-0.07), segments=32, material=BLUE))
    parts.append(common.cylinder(R + 0.002, R + 0.002, 0.012, at(z=0.056), segments=32, material=BLUE))
    # Rounded red cap with the web shooter nozzle sticking out of it.
    parts.append(common.cylinder(R, R * 0.7, 0.03, at(z=0.07), segments=32, material=RED))
    parts.append(common.cylinder(0.016, 0.016, 0.03, at(z=0.1), segments=20, material=SILVER))
    parts.append(common.cylinder(0.011, 0.011, 0.006, at(z=0.116), segments=20, material=BLACK))
    parts.append(common.cylinder(0.019, 0.019, 0.008, at(z=0.088), segments=20, material=BLACK))

    # Black web pattern: rings around the glove, and lines running up it.
    for z in (-0.03, 0.0, 0.03):
        parts.append(common.cylinder(R + 0.001, R + 0.001, 0.0035, at(z=z), segments=32, material=BLACK))
    for k in range(10):
        a = k * math.tau / 10
        m = at(math.cos(a) * (R + 0.0006), math.sin(a) * (R + 0.0006), 0.0) @ Matrix.Rotation(a, 4, "Z")
        parts.append(common.box((0.0015, 0.0035, 0.092), m, material=BLACK))

    # The wrist-mounted shooter housing on the back, with its trigger button.
    parts.append(common.box((0.03, 0.02, 0.07), at(y=R + 0.007, z=-0.012), material=SILVER, bevel=0.004))
    parts.append(common.box((0.012, 0.01, 0.014), at(y=R + 0.019, z=-0.004), material=RED, bevel=0.002))

    # The spider emblem on the front: a black body and eight legs on a white patch.
    parts.append(common.cylinder(0.026, 0.026, 0.002, at(y=-R - 0.0005) @ Matrix.Rotation(math.pi / 2, 4, "X"),
                                 segments=24, material=WHITE))
    front = -R - 0.0025
    parts.append(common.sphere(1.0, at(y=front, z=-0.002) @ Matrix.Diagonal((0.0055, 0.0035, 0.009, 1.0)), segments=14, rings=8, material=BLACK))
    parts.append(common.sphere(1.0, at(y=front, z=0.01) @ Matrix.Diagonal((0.0038, 0.0032, 0.0038, 1.0)), segments=12, rings=8, material=BLACK))
    for sign in (-1, 1):
        for deg in (-55, -20, 15, 50):
            a = math.radians(deg)
            dx = sign * (0.006 + 0.0085 * math.cos(a))
            dz = 0.0085 * math.sin(a) - 0.002
            m = at(dx, front, dz) @ Matrix.Rotation(-sign * a, 4, "Y")
            parts.append(common.box((0.017, 0.0022, 0.0024), m, material=BLACK))
    return common.merge(scene, "WebSlinger", parts, materials, flat_materials=())


def main():
    scene = common.fresh_scene("WebSlinger")
    materials = common.make_materials("WS_", COLORS, ORDER, roughness=0.45)
    glove = build(scene, materials)

    assets = common.assets_dir(KEY)
    tris = common.export_obj(glove, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Web Slinger - generated by build_web_slinger.py")
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, "web_slinger.blend"), scene)

    # Icon: the glove from the front, tipped a little so the nozzle and emblem both show.
    glove.rotation_euler = (math.radians(-18), math.radians(0), math.radians(-28))
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=0.27, look_at=(0, 0, 0.0),
                       cam_offset=(0, -1, 0.0))
    d = glove.dimensions
    print(f"RESULT {NAME}: {tris} triangles, dimensions {d.x:.3f} x {d.y:.3f} x {d.z:.3f} m")


main()
