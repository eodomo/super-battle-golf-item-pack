"""Builds Captain America's shield: a slightly domed disc of red, white and red rings around a blue center with a
white five-pointed star, and two arm straps on the back.

    Run through the Blender MCP (exec with __file__ set to this path).

Outputs Assets/CapShield/cap_shield.obj/.mtl/_icon.png and blender/CapShield/cap_shield.blend.
The face looks along -Y (Blender), up is +Z, origin at the center of the back. 0.76 m across.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import bmesh  # noqa: E402
import common  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402

KEY = "CapShield"
NAME = "cap_shield"
COLORS = {
    "Red": (0.78, 0.08, 0.1),
    "White": (0.93, 0.93, 0.95),
    "Blue": (0.08, 0.2, 0.62),
    "Strap": (0.22, 0.16, 0.1),
    "Back": (0.55, 0.55, 0.58),
}
ORDER = ["Red", "White", "Blue", "Strap", "Back"]
RED, WHITE, BLUE, STRAP, BACK = range(5)
FACE = Matrix.Rotation(math.radians(90), 4, "X")  # cylinder axis Z -> facing -Y


def ring(radius, y, depth, material):
    return common.cylinder(radius, radius, depth, Matrix.Translation((0, y, 0)) @ FACE, 64, material)


def star(outer, inner, y, depth, material):
    bm = bmesh.new()
    verts = []
    for k in range(10):
        a = math.pi / 2 + k * math.pi / 5
        r = outer if k % 2 == 0 else inner
        verts.append(bm.verts.new((math.cos(a) * r, y, math.sin(a) * r)))
    face = bm.faces.new(verts)
    result = bmesh.ops.extrude_face_region(bm, geom=[face])
    moved = [v for v in result["geom"] if isinstance(v, bmesh.types.BMVert)]
    bmesh.ops.translate(bm, vec=Vector((0, -depth, 0)), verts=moved)
    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    return common.set_material(bm, material)


def build():
    p = [
        # The back plate, then each ring a little further forward: a shallow stepped dome.
        ring(0.38, 0.0, 0.02, BACK),
        ring(0.38, -0.015, 0.02, RED),
        ring(0.305, -0.026, 0.02, WHITE),
        ring(0.23, -0.036, 0.02, RED),
        ring(0.155, -0.045, 0.02, BLUE),
        star(0.15, 0.06, -0.055, 0.008, WHITE),
    ]
    # Arm straps across the back.
    for z in (0.09, -0.09):
        p.append(common.box((0.3, 0.03, 0.05), Matrix.Translation((0, 0.03, z)), STRAP, bevel=0.006))
        for x in (0.15, -0.15):
            p.append(common.box((0.03, 0.03, 0.05), Matrix.Translation((x, 0.015, z)), STRAP, bevel=0.006))
    return p


def main():
    scene = common.fresh_scene("CapShield")
    mats = common.make_materials("CS_", COLORS, ORDER, roughness=0.35)
    obj = common.merge(scene, "CapShield", build(), mats, flat_materials=(RED, WHITE, BLUE, BACK, STRAP))
    assets = common.assets_dir(KEY)
    tris = common.export_obj(obj, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Captain America's Shield - generated by build_cap_shield.py")
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=0.86,
                       look_at=(0, -0.03, 0), cam_offset=(0.35, -1.2, 0.3))
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    return f"{NAME}: {tris} triangles, dims {tuple(round(v, 3) for v in obj.dimensions)}"


RESULT = main()
print("RESULT", RESULT)
