"""Builds the Portal Gun model (a handheld portal device: white body, black prongs, glowing core).

    blender --background --factory-startup --python blender/PortalGun/build_portal_gun.py

Outputs Assets/PortalGun/portal_gun.obj/.mtl/_icon.png and blender/PortalGun/portal_gun.blend.
Forward is +Y (Blender), up is +Z, origin at the grip.
"""
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import common  # noqa: E402
from mathutils import Matrix, Vector  # noqa: E402

KEY = "PortalGun"
NAME = "portal_gun"
COLORS = {
    "White": (0.93, 0.93, 0.91),
    "Black": (0.11, 0.11, 0.12),
    "Grey": (0.46, 0.48, 0.52),
    "Glow": (0.45, 0.80, 1.00),
}
ORDER = ["White", "Black", "Grey", "Glow"]
WHITE, BLACK, GREY, GLOW = range(4)


def along_y(x, y, z):
    """Matrix for a cone/cylinder (built along Z) lying along +Y, centered at (x, y, z)."""
    return Matrix.Translation((x, y, z)) @ Matrix.Rotation(math.radians(-90), 4, "X")


def main():
    scene = common.fresh_scene("PortalGun")
    materials = common.make_materials("PG_", COLORS, ORDER, roughness=0.35)
    parts = []
    body_z = 0.075  # body axis height above the grip origin

    # Main body: a white capsule-ish shell, wider at the back.
    parts.append(common.cylinder(0.068, 0.058, 0.26, along_y(0, -0.02, body_z), segments=28, material=WHITE))
    parts.append(common.sphere(0.068, Matrix.Translation((0, -0.15, body_z)) @ Matrix.Diagonal((1, 0.7, 1, 1)), segments=28, rings=14, material=WHITE))
    # Black rear cap and the black collar at the front.
    parts.append(common.cylinder(0.05, 0.05, 0.03, along_y(0, -0.205, body_z), segments=24, material=BLACK))
    parts.append(common.cylinder(0.064, 0.07, 0.04, along_y(0, 0.125, body_z), segments=28, material=BLACK))
    # Clear chamber on top (grey) with black bands.
    parts.append(common.cylinder(0.026, 0.026, 0.2, along_y(0, -0.02, body_z + 0.068), segments=16, material=GREY))
    for y in (-0.09, -0.02, 0.05):
        parts.append(common.cylinder(0.03, 0.03, 0.014, along_y(0, y, body_z + 0.068), segments=16, material=BLACK))

    # Three prongs around the barrel, pointing forward and curving in toward the core.
    for k in range(3):
        angle = math.radians(90 + k * 120)
        radial = Vector((math.cos(angle), 0.0, math.sin(angle)))
        base = Vector((0, 0.15, body_z)) + radial * 0.055
        tip = Vector((0, 0.26, body_z)) + radial * 0.03
        direction = tip - base
        rot = direction.to_track_quat("Z", "Y").to_matrix().to_4x4()
        mid = (base + tip) / 2
        parts.append(common.cylinder(0.016, 0.006, direction.length, Matrix.Translation(mid) @ rot, segments=10, material=BLACK))
        parts.append(common.sphere(0.017, Matrix.Translation(base), segments=10, rings=6, material=WHITE))

    # Glowing core between the prongs.
    parts.append(common.sphere(0.034, Matrix.Translation((0, 0.19, body_z)), segments=18, rings=12, material=GLOW))

    # Grip under the body, angled back, plus a trigger guard block.
    grip = Matrix.Translation((0, -0.07, 0.0)) @ Matrix.Rotation(math.radians(-15), 4, "X")
    parts.append(common.box((0.045, 0.06, 0.13), grip, material=BLACK))
    parts.append(common.box((0.03, 0.05, 0.03), Matrix.Translation((0, -0.01, 0.03)), material=GREY))

    gun = common.merge(scene, "PortalGun", parts, materials)

    assets = common.assets_dir(KEY)
    tris = common.export_obj(gun, os.path.join(assets, f"{NAME}.obj"), os.path.join(assets, f"{NAME}.mtl"),
                             COLORS, ORDER, "Portal Gun - generated by build_portal_gun.py")
    common.render_icon(scene, os.path.join(assets, f"{NAME}_icon.png"), ortho_scale=0.54,
                       look_at=(0, 0.0, 0.07), cam_offset=(0.9, -0.35, 0.45))
    common.save_blend(os.path.join(common.ROOT, "blender", KEY, f"{NAME}.blend"), scene)
    d = gun.dimensions
    print(f"RESULT {NAME}: {tris} triangles, dimensions {d.x:.3f} x {d.y:.3f} x {d.z:.3f} m")


main()
